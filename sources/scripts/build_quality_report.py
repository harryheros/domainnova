#!/usr/bin/env python3
"""
build_quality_report.py — data/QUALITY.md, the dataset's quality page.

Written at the end of every build from files the build already produced,
so it never disagrees with them:

  dist/domains_<region>.txt      what is published
  data/domains_metadata.csv      tier and origin of every domain
  data/stats.json                resolver counts, foreign edges, lifecycle
  data/seed_health.json          how many sampled seeds still land in region
  sources/manual/removed.csv     agent-nominated domains removed on review

The page carries no time of its own (only the build's), so an unchanged
build leaves it unchanged.

    python sources/scripts/build_quality_report.py
"""
from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
REGIONS = ("cn", "hk", "mo", "tw", "jp", "kr", "sg")
TIERS = ("seed", "extended", "discovery")
ORIGINS = ("manual", "ip-neighbor", "link-crawl", "ct-logs")
REMOVAL_REASONS = {
    "shared-host": "found on a shared-hosting IP (20+ unrelated sites)",
    "covered-by": "a subdomain of a name already listed",
    "reduced-to": "replaced by its registrable name",
    "public-suffix": "a public suffix, not a registrable name",
    "free-subdomain": "a name under a free subdomain or hosting service",
    "numeric-throwaway": "a numeric throwaway name",
    "adult-gambling": "adult or gambling site",
}


def _json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _csv(path: Path) -> list[dict]:
    try:
        with path.open(encoding="utf-8", newline="") as fh:
            return list(csv.DictReader(fh))
    except OSError:
        return []


def published(root: Path) -> dict[str, list[str]]:
    out = {}
    for r in REGIONS:
        p = root / "dist" / f"domains_{r}.txt"
        lines = p.read_text(encoding="utf-8").splitlines() if p.exists() else []
        out[r] = [x.strip() for x in lines if x.strip() and not x.startswith("#")]
    return out


def _pct(n: int, total: int) -> str:
    return f"{100 * n / total:.1f}%" if total else "–"


def _table(head: list[str], rows: list[list], align: str = "") -> list[str]:
    """align: one letter per column, l or r (default: first left, rest right)."""
    align = align or "l" + "r" * (len(head) - 1)
    out = ["| " + " | ".join(head) + " |",
           "|" + "|".join("---:" if a == "r" else "---" for a in align) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return out


def _n(x: int) -> str:
    return f"{x:,}"


def build(root: Path = ROOT) -> str:
    stats = _json(root / "data" / "stats.json")
    seed_health = _json(root / "data" / "seed_health.json").get("results", {})
    meta = {row["domain"]: row for row in _csv(root / "data" / "domains_metadata.csv")}
    removed = _csv(root / "sources" / "manual" / "removed.csv")
    dist = published(root)
    total = sum(len(v) for v in dist.values())

    def tier(d: str) -> str:
        src = meta.get(d, {}).get("source", "")
        return "seed" if src.startswith("seed_") else (src or "unknown")

    def origin(d: str) -> str:
        return meta.get(d, {}).get("origin") or "unknown"

    L = [
        "# DomainNova data quality",
        "",
        ("Generated by every build from the published lists and the build's own records "
        "(`build_quality_report.py`). Do not edit by hand."),
        "",
        f"- Build: {stats.get('generated_at', 'unknown')}",
        "- To cite this version of the data, use this build's commit; see the README.",
        "",
        "## Published domains, by tier",
        "",
        ("Seeds are curated by hand and placed in their region directly; extended and "
        "discovery domains are published only on this build's DNS and IP checks."),
        "",
    ]
    rows = []
    for r in REGIONS:
        c = Counter(tier(d) for d in dist[r])
        rows.append([r.upper(), _n(len(dist[r]))] + [_n(c[t]) for t in TIERS])
    allc = Counter(tier(d) for v in dist.values() for d in v)
    rows.append(["**All**", f"**{_n(total)}**"] + [f"**{_n(allc[t])}**" for t in TIERS])
    L += _table(["Region", "Published", "Seed", "Extended", "Discovery"], rows)

    L += ["", "## How the published domains were found", "",
          ("`manual`: curated by hand. The others are the discovery agent that first "
          "nominated the domain (`origin` in `data/domains_metadata.*`). No domain is "
          "taken from a third-party list."), ""]
    oc = Counter(origin(d) for v in dist.values() for d in v)
    names = list(ORIGINS) + sorted(set(oc) - set(ORIGINS))
    L += _table(["Origin", "Published", "Share"],
                [[f"`{o}`", _n(oc[o]), _pct(oc[o], total)] for o in names if oc[o] or o in ORIGINS])

    res = stats.get("resolver", {})
    rtotal = sum(res.values())
    L += ["", "## Which resolver answered", "",
          ("All domains checked in this build. `own`: our resolver, which asks each "
          "domain's own name servers; `public`: a public resolver with client subnet "
          "support, used only when ours had no answer; `fallback`: last resort; "
          "`unresolved`: no address."), ""]
    L += _table(["Resolver", "Domains", "Share"],
                [[f"`{k}`", _n(res.get(k, 0)), _pct(res.get(k, 0), rtotal)]
                 for k in ("own", "public", "fallback", "unresolved")])

    fe = stats.get("foreign_edge", {})
    nets, demoted = fe.get("networks", []), fe.get("demoted", [])
    L += ["", "## Foreign services' in-region edges", "",
          ("Each build resolves sentinel domains of global services; the /24 networks where "
          "they land inside a region are not counted as regional hosting. A domain placed "
          "in a region only through such a network is not published."), "",
          f"- Networks: {len(nets)}" + (f" ({', '.join(f'`{n}`' for n in nets)})" if nets else ""),
          f"- Domains held back: {len(demoted)}" + (f" ({', '.join(f'`{d}`' for d in demoted)})" if demoted else "")]

    L += ["", "## Seed health", "",
          ("A sample of every seed list is checked against IPNova each build. *In region* "
          "counts seeds whose addresses, or whose known identity, still place them in "
          "their region; seeds are never moved automatically."), ""]
    rows = []
    for name, h in sorted(seed_health.items(), key=lambda kv: REGIONS.index(kv[1].get("region", "").lower())
                          if kv[1].get("region", "").lower() in REGIONS else 99):
        rows.append([h.get("region", name), _n(h.get("sampled", 0)), _n(h.get("resolved", 0)),
                     _n(h.get("consistent", 0)), _pct(h.get("consistent", 0), h.get("sampled", 0)),
                     h.get("status", "")])
    L += _table(["Seed list", "Sampled", "Resolved", "In region", "Rate", "Status"], rows, "lrrrrl") if rows \
        else ["No seed check in this build."]

    lv = stats.get("local_view") or {}
    if lv:
        L += ["", "## Regional view (trial, not published)", "",
              ("The build asks where a domain is hosted as a client in China would. A trial "
               "asks again as a client in the domain's own region, for seeds and for names "
               "under the region's ccTLD; a global service also answers from its node in a "
               "region asked that way, so each answer must pass guards before it counts, and "
               "nothing from it is published yet. Method: `sources/scripts/_local_view.py`."),
              ""]
        if lv.get("skipped"):
            L += [f"Skipped in this build: {lv['skipped']}."]
        else:
            seeds = lv.get("seeds", {})
            why = lv.get("seed_verdicts", {})
            if seeds:
                L += ["Seeds found in their own region (calibration: they are curated as being there):", ""]
                L += _table(["Region", "Seeds checked", "Found in region", "Share", "Not found: why"],
                            [[r, _n(v["checked"]), _n(v["local"]), _pct(v["local"], v["checked"]),
                              ", ".join(f"`{k}` {_n(c)}" for k, c in why.get(r, {}).items()) or "–"]
                             for r, v in seeds.items()])
                L += [""]
            subnets = lv.get("subnets", {})
            if subnets:
                kind = lv.get("subnet_kind", {})
                fallback = [r for r in subnets if kind.get(r) == "largest range"]
                L += ["- Asked from: " + ", ".join(f"{r} `{s}`" for r, s in subnets.items())
                      + (f" ({', '.join(fallback)}: largest IPNova range, no consumer ISP block)"
                         if fallback else "")]
            ctl = lv.get("controls", {})
            L += [f"- Global services used as controls: {_n(ctl.get('passed', 0))} of "
                  f"{_n(ctl.get('checked', 0))} checks passed the guards (should be 0)"
                  + (f": {', '.join(f'`{x}`' for x in ctl.get('passed_names', [])[:10])}"
                     if ctl.get("passed_names") else "")]
            verdicts = lv.get("verdicts", {})
            if verdicts:
                L += ["- Other domains checked: " + ", ".join(
                    f"`{k}` {_n(v)}" for k, v in verdicts.items())]
            would = lv.get("would_add", {})
            pend = lv.get("pending", {})
            L += [f"- Would be added after {lv.get('required_weeks', 2)} weeks in a row: "
                  + (", ".join(f"{r} {_n(len(v))}" for r, v in would.items()) or "none yet")
                  + (" (waiting: " + ", ".join(f"{r} {_n(v)}" for r, v in pend.items()) + ")"
                     if pend else "")]
            for r, names in would.items():
                shown = ", ".join(f"`{d}`" for d in names[:15])
                more = f" and {_n(len(names) - 15)} more" if len(names) > 15 else ""
                L += [f"  - {r}: {shown}{more}"]

    L += ["", "## This build", ""]
    L += _table(["Event", "Domains"], [
        ["Promoted from discovery to extended", _n(stats.get("auto_promoted", 0))],
        ["Discovery domains removed after failing", _n(stats.get("auto_purged", 0))],
        ["Dead domains removed", _n(stats.get("auto_dead_removed", 0))],
        ["Kept at their last placement (no answer this build)", _n(stats.get("sticky_retained", 0))],
        ["Seeds listed for manual review", _n(stats.get("seeds_needing_review", 0))],
    ])

    rc = Counter(row.get("reason", "").split(":", 1)[0] for row in removed)
    reduced = rc.get("reduced-to", 0)
    L += ["", "## Removed on review", "",
          (f"When the discovery rules are tightened, the domains agents had already nominated "
          f"are checked again: {_n(len(removed) - reduced)} were removed and {_n(reduced)} "
          "replaced by their registrable name. Each is listed with its reason in "
          "[`sources/manual/removed.csv`](../sources/manual/removed.csv). Domains curated by "
          "hand are never removed this way."), ""]
    if removed:
        L += _table(["Reason", "Meaning", "Domains"],
                    [[f"`{k}`", REMOVAL_REASONS.get(k, ""), _n(v)] for k, v in rc.most_common()],
                    "llr")
    return "\n".join(L) + "\n"


def main() -> None:
    out = ROOT / "data" / "QUALITY.md"
    out.write_text(build(), encoding="utf-8")
    print(f"[+] Wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
